-- A14 追加：提测记录上的「最近一次被轮询看到的时间」。
--
-- 只追加一列，不改 A5/A17 已定的字段与索引。
--
-- 为什么需要它：轮询任务单轮只处理固定条数（默认 50）。没有这一列时只能按创建时间取
-- 最早的 50 条，最新投递的提测永远排在后面、永远轮不到（QA 在功能检测里验出的问题）。
-- 有了它，挑活改成「最久没被轮询的优先」，空值排在最前，新投递的下一轮就会被轮到。
--
-- 轮询失败也会写这一列：它表示「这一轮看过它了」。否则一条一直失败的提测会占住队首，
-- 把其他提测饿死。不加索引：查询先按状态（已有索引）过滤到在跑的少量提测，排序开销可忽略。

